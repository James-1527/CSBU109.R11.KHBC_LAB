// Swagger / OpenAPI 3.0 configuration
const swaggerJSDoc = require('swagger-jsdoc');
const swaggerUi = require('swagger-ui-express');

const options = {
  definition: {
    openapi: '3.0.0',
    info: {
      title: 'RESTful API Documentation - Web & Database Lab 3',
      version: '1.0.0',
      description: 'Interactive API documentation auto-generated by Swagger UI for the Sales Management application'
    },
    servers: [
      { url: 'http://localhost:3000/api', description: 'Development Local Server' }
    ],
    tags: [
      { name: 'Products', description: 'Product management endpoints' },
      { name: 'Categories', description: 'Category management endpoints' }
    ],
    components: {
      parameters: {
        idParam: {
          name: 'id',
          in: 'path',
          required: true,
          description: 'MongoDB _id of the resource',
          schema: { type: 'string', example: '6aa7c27316747184e0b762ac' }
        }
      },
      schemas: {
        Error: {
          type: 'object',
          properties: {
            success: { type: 'boolean', example: false },
            message: { type: 'string', example: 'No product found with the given ID' },
            error: { type: 'string', example: 'Product name cannot be empty' }
          }
        }
      }
    }
  },
  // Files to scan for @swagger comments (relative to the folder you run "node server.js" from)
  apis: ['./routes/*.js', './models/*.js']
};

const swaggerSpec = swaggerJSDoc(options);

const setupSwagger = (app) => {
  app.use('/api-docs', swaggerUi.serve, swaggerUi.setup(swaggerSpec));
  console.log('Swagger UI documentation is ready at: http://localhost:3000/api-docs');
};

module.exports = setupSwagger;